"""Build the warming-stripes graphics used across the site.

Reads data/gistemp-annual.csv (NASA GISTEMP global annual temperature
anomalies) and writes:
  _theme/stripes.css     a CSS gradient with one hard-edged stripe per year
  assets/favicon.svg     a square of the most recent 40 years

Colour scale follows Ed Hawkins' warming stripes: anomalies relative to the
1971-2000 mean, scaled to +/- 2.6 standard deviations of 1901-2000, mapped
onto 16 blue-to-red colours.

To update after a new year of data, add a row to the CSV and run:
    python3 scripts/make_stripes.py
(The GitHub workflow also runs this on every build.)
"""

import csv
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

COLOURS = [
    "#08306b", "#08519c", "#2171b5", "#4292c6", "#6baed6", "#9ecae1",
    "#c6dbef", "#deebf7", "#fee0d2", "#fcbba1", "#fc9272", "#fb6a4a",
    "#ef3b2c", "#cb181d", "#a50f15", "#67000d",
]


def load():
    with open(ROOT / "data" / "gistemp-annual.csv", newline="") as f:
        return [(int(r["year"]), float(r["anomaly"])) for r in csv.DictReader(f)]


def colour_for(value, sd):
    lo, hi = -2.6 * sd, 2.6 * sd
    t = (min(max(value, lo), hi) - lo) / (hi - lo)
    return COLOURS[min(int(t * len(COLOURS)), len(COLOURS) - 1)]


def main():
    rows = load()
    ref = statistics.mean(v for y, v in rows if 1971 <= y <= 2000)
    sd = statistics.pstdev(v for y, v in rows if 1901 <= y <= 2000)
    stripes = [(y, colour_for(v - ref, sd)) for y, v in rows]

    n = len(stripes)
    stops = []
    for i, (_, c) in enumerate(stripes):
        a, b = 100 * i / n, 100 * (i + 1) / n
        stops.append(f"{c} {a:.4f}% {b:.4f}%")
    first, last = stripes[0][0], stripes[-1][0]
    css = (
        f"/* Generated by scripts/make_stripes.py from NASA GISTEMP, {first}-{last}. */\n"
        f".stripes {{ background-image: linear-gradient(to right, {', '.join(stops)}); }}\n"
    )
    (ROOT / "_theme" / "stripes.css").write_text(css)

    recent = stripes[-40:]
    w = 32 / len(recent)
    rects = "".join(
        f'<rect x="{i * w:.3f}" y="0" width="{w + 0.05:.3f}" height="32" fill="{c}"/>'
        for i, (_, c) in enumerate(recent)
    )
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">'
        '<clipPath id="r"><rect width="32" height="32" rx="6"/></clipPath>'
        f'<g clip-path="url(#r)">{rects}</g></svg>\n'
    )
    (ROOT / "assets" / "favicon.svg").write_text(svg)
    print(f"Stripes: {first}-{last} ({n} years)")


if __name__ == "__main__":
    main()
